import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const toolDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.dirname(toolDirectory);
const garageDataDirectory = path.join(repositoryRoot, "data", "garage");
const floorNumbers = [2, 3, 4, 5];
const outputPath = path.join(garageDataDirectory, "registry-bundle.js");
const registries = {};

for (const floorNumber of floorNumbers) {
  const registryPath = path.join(garageDataDirectory, `floor-${floorNumber}.json`);
  const registry = JSON.parse(await readFile(registryPath, "utf8"));
  const expectedFloor = `F${floorNumber}`;

  if (registry.floor !== expectedFloor) {
    throw new Error(
      `${registryPath} declares floor ${JSON.stringify(registry.floor)}; expected ${expectedFloor}.`,
    );
  }
  registries[expectedFloor] = registry;
}

const moduleSource = [
  "// Generated by garage-plans-tools/bundle_garage_registries.mjs.",
  "// Edit the floor JSON registries, then rerun that script.",
  `const registries = ${JSON.stringify(registries)};`,
  "export const GARAGE_REGISTRIES = Object.freeze(registries);",
  "export default GARAGE_REGISTRIES;",
  "",
].join("\n");

await writeFile(outputPath, moduleSource, "utf8");
console.log(`Bundled ${floorNumbers.length} registries into ${outputPath}`);
